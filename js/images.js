/* DOLFIN PROJECTS — image loader.
   .ph[data-img]  : photo/illustration slots. js/photos-manifest.js (generated by tools/build.js)
                    maps each slot to a real photo if one exists, otherwise to an original illustration.
   [data-logo]    : brand logo slots. If assets/images/brands/<brand-id>.(png|svg|jpg|webp) exists
                    it is shown; otherwise the brand name is shown as text. */
(function () {
  window.dolfinLoadImages = function (root) {
    var M = window.DOLFIN_PHOTOS || {}, r = root || document;
    r.querySelectorAll(".ph[data-img]:not([data-done])").forEach(function (el) {
      var f = M[el.getAttribute("data-img")]; el.setAttribute("data-done", "1");
      if (!f) return;
      el.style.backgroundImage = "url('" + f + "')";
      el.style.backgroundSize = "cover"; el.style.backgroundPosition = "center";
      el.classList.add("has-photo");
    });
    r.querySelectorAll("[data-logo]:not([data-done])").forEach(function (el) {
      el.setAttribute("data-done", "1");
      var f = M["assets/images/brands/" + el.getAttribute("data-logo")]; if (!f) return;
      var n = el.getAttribute("data-name") || "";
      el.innerHTML = '<img src="' + f + '" alt="' + n.replace(/"/g, "&quot;") + ' logo" loading="lazy">';
      el.classList.add("has-logo");
    });
  };
  document.addEventListener("DOMContentLoaded", function () { window.dolfinLoadImages(); });
})();
